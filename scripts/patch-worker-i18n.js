// ─── Merge into locale files ──────────────────────────────────────────────────
const LOCALES_DIR = path.join(__dirname, "..", "src", "i18n", "locales");

let ok = 0;
let fail = 0;

for (const [lang, patch] of Object.entries(PATCHES)) {
  const filePath = path.join(LOCALES_DIR, `${lang}.json`);

  if (!fs.existsSync(filePath)) {
    console.warn(`⚠️  ${lang}.json not found at ${filePath} — skipping`);
    fail++;
    continue;
  }

  try {
    const existing = JSON.parse(fs.readFileSync(filePath, "utf8"));
    const merged = { ...existing, ...patch };
    fs.writeFileSync(filePath, JSON.stringify(merged, null, 2) + "\n", "utf8");
    console.log(
      `✅  Patched ${lang}.json — added workerCat, workerWallet, workerEarnings, workerReviews`,
    );
    ok++;
  } catch (err) {
    console.error(`❌  Failed to patch ${lang}.json:`, err.message);
    fail++;
  }
}

console.log(`\nDone: ${ok} patched, ${fail} failed.`);
if (fail > 0) process.exit(1);
