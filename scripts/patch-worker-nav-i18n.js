// ─── Merge into locale files ──────────────────────────────────────────────────
const LANGS = ["en", "ar", "es", "fr", "ha", "ig", "pt", "yo", "zh"];
let ok = 0,
  fail = 0;

for (const lang of LANGS) {
  const filePath = path.join(LOCALES_DIR, `${lang}.json`);
  if (!fs.existsSync(filePath)) {
    console.warn(`⚠️  ${lang}.json not found — skipping`);
    fail++;
    continue;
  }
  try {
    const existing = JSON.parse(fs.readFileSync(filePath, "utf8"));

    // Merge nav keys INTO existing nav object
    existing.nav = { ...existing.nav, ...(NAV_PATCH[lang] ?? {}) };

    // Add screenSub namespace
    existing.screenSub = {
      ...(existing.screenSub ?? {}),
      ...(SCREEN_SUB_PATCH[lang]?.screenSub ?? {}),
    };

    fs.writeFileSync(
      filePath,
      JSON.stringify(existing, null, 2) + "\n",
      "utf8",
    );
    console.log(`✅  ${lang}.json — nav + screenSub patched`);
    ok++;
  } catch (err) {
    console.error(`❌  ${lang}.json:`, err.message);
    fail++;
  }
}
console.log(`\nDone: ${ok} patched, ${fail} failed.`);
if (fail > 0) process.exit(1);
